#!/usr/bin/env node
// Generates Skins/FlyingTulip/Main.ini: node tools/gen_main_ini.js (or bun). Edit this file, not Main.ini.
//
// The skin follows the Omarchy panel: a dark rounded panel, a header (logo, "Flying Tulip", the wallet shown, the
// switch / settings / refresh buttons), three pill tabs, rounded cards, and a footer. Every card, pill, bar and button
// box is drawn by one Shape meter (MeterCanvas) that the script fills; the text and chart meters sit on top of it and
// are placed by the script too (FlyingTulip.lua, "layout"). Meter positions below are only the starting point.
const fs = require("fs"), path = require("path")
const OUT = path.join(__dirname, "..", "Skins", "FlyingTulip", "Main.ini")
const VERSION = (fs.readFileSync(path.join(__dirname, "..", "RMSKIN.ini"), "utf8").match(/^Version=(.+)$/m) || [])[1]
const SITE = "https://flyingtulip.com/"
const P = {
  fees: SITE + "statistics/", health: SITE + "lend/dashboard/", portfolio: SITE + "trade/portfolio/",
  rewards: SITE + "rewards/", points: SITE + "rewards/leaderboard/", pointsActivity: SITE + "rewards/my-activity/",
  put: SITE + "allocation/positions/", market: SITE + "trade/?symbol=FT-ftUSD&chainId=1&marketType=spot"
}
const L = []
const sec = (name, opts) => { L.push("", "[" + name + "]"); for (const [k, v] of Object.entries(opts)) if (v !== undefined) L.push(k + "=" + v) }
const open = (el, url) => `[!CommandMeasure MeasureScript "OpenLink('${el}','${url}')"]`
const lua = call => `[!CommandMeasure MeasureScript "${call}"]`
// a text meter: style, link element + url (or a script call), extra options
const text = (name, style, el, url, extra) => sec(name, Object.assign({ Meter: "String", MeterStyle: style, X: 14, Y: 100, Text: "", Hidden: 1 },
  extra || {}, { LeftMouseUpAction: el ? open(el, url) : (extra && extra.LeftMouseUpAction) }))

L.push("; Generated by tools/gen_main_ini.js: edit that script, not this file.")
sec("Rainmeter", {
  Update: 1000, AccurateText: 1, DynamicWindowSize: 1,
  OnRefreshAction: lua("OnLoaded()"),
  ContextTitle: "Wallets and settings...", ContextAction: lua("OpenWallets(1)"),
  ContextTitle2: "Add a wallet...", ContextAction2: lua("OpenWallets(2)"),
  ContextTitle3: "Show the next wallet", ContextAction3: lua("NextWallet()"),
  ContextTitle4: "Remove the wallet shown", ContextAction4: lua("RemoveShownWallet()"),
  ContextTitle5: "Edit the settings file (alerts, refresh)", ContextAction5: '["notepad.exe" "#@#Settings.inc"]',
  ContextTitle6: "Open flyingtulip.com", ContextAction6: open("menu-open-site", SITE),
  ContextTitle7: "Advanced: anonymous usage stats on or off", ContextAction7: lua("ToggleAnalytics()"),
})
L.push("; the mouse coming over the skin counts as opening it (at most once per 30 minutes) in the anonymous usage stats",
  "MouseOverAction=" + lua("PanelOpen()"))
sec("Metadata", {
  Name: "Flying Tulip", Author: "Flying Tulip",
  Information: "FT market price, 24h application fees and, for the wallets you set, health factor with liquidation alerts, PnL, FT earned, points, ftPUT gain and positions. Public API only (api.flyingtulip.com), no keys. Not financial advice.",
  Version: VERSION,
  License: "MIT. The Flying Tulip name and logo are trademarks of Flying Tulip and are not covered by the MIT license.",
})
sec("Variables", { "@Include": "#@#Settings.inc", RankPage: 7 })
L.push("; set by the script: the wallet shown, the one the background health check reads, the FT earned history range",
  "CurWallet=", "WatchWallet=", "HistRange=30d", "", "@Include2=#@#Data.inc")

// ---- styles (colours of the Omarchy panel: text #e4e4e7, sub #a1a1aa, faint #71717a, tulip #7559ff / #b7b1ff)
L.push("", "; ---------------------------------------------------------------- styles")
const base = { FontFace: "Segoe UI", AntiAlias: 1, StringAlign: "Left", ClipString: 1 }
sec("StyCap", Object.assign({}, base, { FontSize: 6.5, StringStyle: "Bold", FontColor: "113,113,122,255", W: 300, H: 14 }))
sec("StyTitle", Object.assign({}, base, { FontSize: 10, StringStyle: "Bold", FontColor: "228,228,231,255" }))
sec("StyText", Object.assign({}, base, { FontSize: 8, FontColor: "228,228,231,255", W: 200, H: 16 }))
sec("StySub", Object.assign({}, base, { FontSize: 7.5, FontColor: "161,161,170,255", W: 160, H: 14 }))
sec("StySmall", Object.assign({}, base, { FontSize: 7, FontColor: "113,113,122,255", W: 120, H: 13 }))
sec("StyValue", Object.assign({}, base, { FontSize: 13, StringStyle: "Bold", FontColor: "228,228,231,255", W: 160, H: 24 }))
sec("StyHero", Object.assign({}, base, { FontSize: 11, StringStyle: "Bold", FontColor: "228,228,231,255", W: 110, H: 20 }))
sec("StyPill", Object.assign({}, base, { FontSize: 8, FontColor: "161,161,170,255", StringAlign: "CenterCenter", W: 70, H: 24 }))
sec("StyIcon", Object.assign({}, base, { FontFace: "Segoe UI Symbol", FontSize: 11, FontColor: "161,161,170,255", StringAlign: "CenterCenter", W: 30, H: 30, ClipString: 0 }))

// ---- logic
L.push("", "; ---------------------------------------------------------------- logic")
sec("MeasureScript", { Measure: "Script", ScriptFile: "#@#Lua\\FlyingTulip.lua" })
L.push("; The settings box (the InputText plugin ships with Rainmeter). It appears under the tabs.",
  "; Batch 1 edits the whole wallet list, batch 2 adds one wallet (its box starts empty).")
sec("MeasureInput", {
  Measure: "Plugin", Plugin: "InputText", X: 14, Y: 100, W: 352, H: 26, SolidColor: "58,50,110,255", FontColor: "228,228,231,255",
  FontFace: "Consolas", FontSize: 10, StringAlign: "Left", FocusDismiss: 1, DefaultValue: "#Wallets#", DynamicVariables: 1,
  Command1: lua("SetWallets('$UserInput$')"),
  Command2: lua("AddWallet('$UserInput$')") + ' DefaultValue=""',
  OnDismissAction: lua("Render()"),
})

// ---- panel, canvas, header (always shown)
L.push("", "; ---------------------------------------------------------------- panel and header")
sec("MeterBackground", { Meter: "Shape", X: 0, Y: 0, Shape: "Rectangle 0,0,380,520,14 | Fill Color 14,14,17,245 | StrokeWidth 1 | Stroke Color 117,89,255,110" })
L.push("; every card, pill, bar and button box (the script writes Shape, Shape2, ...)")
sec("MeterCanvas", { Meter: "Shape", X: 0, Y: 0, Shape: "Rectangle 0,0,1,1 | Fill Color 0,0,0,0 | StrokeWidth 0" })
sec("MeterLogo", { Meter: "Image", ImageName: "#@#logo.png", X: 19, Y: 19, W: 20, H: 20, LeftMouseUpAction: open("header-logo", SITE) })
text("MeterTitle", "StyTitle", "header-title", SITE, { X: 54, Y: 14, Text: "Flying Tulip", W: 180, H: 18, Hidden: 0 })
L.push("; the wallet shown and which of several it is (\"0xd67d..6fcd  1/2\")")
text("MeterSub", "StySub", "header-wallet", P.portfolio, { X: 54, Y: 32, Text: "Market, fees and your account", W: 180, Hidden: 0 })
sec("MeterSwitch", { Meter: "String", MeterStyle: "StyIcon", X: 275, Y: 29, Text: "[\\x21C4]", Hidden: 1, ToolTipText: "Show the next wallet", LeftMouseUpAction: lua("NextWallet()") })
sec("MeterCog", { Meter: "String", MeterStyle: "StyIcon", X: 313, Y: 29, Text: "[\\x2699]", ToolTipText: "Wallets and settings (right-click the skin for more)", LeftMouseUpAction: lua("OpenWallets(1)") })
sec("MeterBtnRefresh", { Meter: "String", MeterStyle: "StyIcon", X: 351, Y: 29, Text: "[\\x21BB]", ToolTipText: "Refresh", LeftMouseUpAction: lua("ManualRefresh()") })
L.push("; a low health factor: amber or red, right of the tabs")
text("MeterBanner", "StySmall", "banner-hf", P.health, { X: 366, Y: 70, W: 150, StringAlign: "Right", StringStyle: "Bold", FontColor: "245,165,36,255", Hidden: 0 })
for (const [n, t, x, w] of [["Market", "market", 14, 64], ["Account", "account", 84, 70], ["Positions", "positions", 160, 78]])
  sec("MeterTab" + n, { Meter: "String", MeterStyle: "StyPill", X: x + w / 2, Y: 76, W: w, Text: n, LeftMouseUpAction: lua(`ShowTab('${t}')`) })

// ---- Market tab
L.push("", "; ---------------------------------------------------------------- Market tab")
text("MeterFeesLbl", "StyCap", "market-fees", P.fees, { Text: "FEES LAST 24H", W: 108 })
text("MeterFeesVal", "StyHero", "market-fees", P.fees)
text("MeterFeesDod", "StySmall", "market-day-over-day", P.fees, { W: 108 })
text("MeterPriceLbl", "StyCap", "market-ft-price", P.market, { Text: "FT PRICE", W: 108, ToolTipText: "FT-ftUSD market price, the traded mark. Not the NAV used for accounting." })
text("MeterPriceVal", "StyHero", "market-ft-price", P.market)
text("MeterPriceChg", "StySmall", "market-ft-price", P.market, { W: 108 })
text("MeterDodLbl", "StyCap", "market-day-over-day", P.fees, { Text: "DAY / DAY", W: 108 })
text("MeterDodVal", "StyHero", "market-day-over-day", P.fees)
text("MeterFeesChartLabel", "StyCap", "market-fees-chart", P.fees, { W: 220 })
text("MeterFeesMax", "StySmall", "market-fees-chart", P.fees, { StringAlign: "Right" })
sec("MeterFeesChart", { Meter: "Shape", X: 26, Y: 200, Hidden: 1, Shape: "Rectangle 0,0,1,1 | Fill Color 0,0,0,0 | StrokeWidth 0", LeftMouseUpAction: open("market-fees-chart", P.fees) })
text("MeterFeesStart", "StySmall", "market-fees-chart", P.fees)
text("MeterFeesEnd", "StySmall", "market-fees-chart", P.fees, { StringAlign: "Right" })
text("MeterFeesLegend", "StySmall", "market-fees", P.fees, { W: 328, FontColor: "161,161,170,255" })
text("MeterPriceChartLabel", "StyCap", "market-price-chart", P.market, { W: 220 })
sec("MeterPriceChart", { Meter: "Shape", X: 26, Y: 350, Hidden: 1, Shape: "Rectangle 0,0,1,1 | Fill Color 0,0,0,0 | StrokeWidth 0", LeftMouseUpAction: open("market-price-chart", P.market) })
text("MeterPriceHi", "StySmall", "market-price-chart", P.market, { W: 60 })
text("MeterPriceLo", "StySmall", "market-price-chart", P.market, { W: 60 })
text("MeterPriceStart", "StySmall", "market-price-chart", P.market)
text("MeterPriceEnd", "StySmall", "market-price-chart", P.market, { StringAlign: "Right" })

// ---- Account tab
L.push("", "; ---------------------------------------------------------------- Account tab")
text("MeterAccountHint", "StyText", "account-hint", SITE, { W: 328, H: 60, ClipString: 2, FontColor: "161,161,170,255" })
text("MeterHfLbl", "StyCap", "account-hf", P.health, { Text: "HEALTH FACTOR", W: 160, ToolTipText: "Health factor per chain. Positions can be liquidated below 1.25." })
text("MeterHfNote", "StySmall", "account-hf", P.health, { Text: "red line = liquidation < 1.25", StringAlign: "Right", W: 170 })
for (let i = 1; i <= 4; i++) {
  text("MeterHfName" + i, "StyText", "account-hf-chain", P.health, { W: 66 })
  text("MeterHfC" + i, "StyText", "account-hf-chain", P.health, { W: 60, StringAlign: "Right", StringStyle: "Bold" })
}
for (const [k, el, url] of [["Pnl", "account-pnl", P.portfolio], ["Earn", "account-ft-earned", P.rewards], ["Points", "account-points", P.points], ["Put", "account-ftput", P.put]]) {
  text("Meter" + k + "Lbl", "StyCap", el, url, { W: 150, ToolTipWidth: 320 })
  text("Meter" + k + "Val", "StyValue", el, url, { W: 150, ToolTipWidth: 320 })
  for (let i = 1; i <= 3; i++) text("Meter" + k + "D" + i, "StySub", el, url, { W: 150 })
}
text("MeterHistLbl", "StyCap", "account-ft-earned-chart", P.rewards, { Text: "FT EARNED OVER TIME", W: 200 })
text("MeterHistNote", "StySmall", "account-ft-earned-chart", P.rewards, { Text: "all chains", StringAlign: "Right", W: 80 })
sec("MeterHistTotal", { Meter: "String", MeterStyle: "StyPill", X: 70, Y: 400, W: 88, H: 22, Hidden: 1, Text: "Total earned", LeftMouseUpAction: lua("SetHistSeries('earned')") })
sec("MeterHistClaimed", { Meter: "String", MeterStyle: "StyPill", X: 160, Y: 400, W: 70, H: 22, Hidden: 1, Text: "Claimed", LeftMouseUpAction: lua("SetHistSeries('claimed')") })
sec("MeterHistChart", { Meter: "Shape", X: 26, Y: 430, Hidden: 1, Shape: "Rectangle 0,0,1,1 | Fill Color 0,0,0,0 | StrokeWidth 0", LeftMouseUpAction: open("account-ft-earned-chart", P.rewards) })
text("MeterHistHi", "StySmall", "account-ft-earned-chart", P.rewards, { W: 60 })
text("MeterHistLo", "StySmall", "account-ft-earned-chart", P.rewards, { W: 60 })
text("MeterHistStart", "StySmall", "account-ft-earned-chart", P.rewards)
text("MeterHistEnd", "StySmall", "account-ft-earned-chart", P.rewards, { StringAlign: "Right" })
text("MeterHistEmpty", "StySub", "account-ft-earned-chart", P.rewards, { W: 300 })
for (const [r, label] of [["7d", "7d"], ["30d", "30d"], ["90d", "90d"], ["all", "All"]])
  sec("MeterRange" + r, { Meter: "String", MeterStyle: "StyPill", X: 40, Y: 500, W: 40, H: 22, Hidden: 1, Text: label, LeftMouseUpAction: lua(`SetHistRange('${r}')`) })
text("MeterDailyLbl", "StyCap", "account-ft-earned-daily", P.rewards, { W: 220 })
text("MeterDailyMax", "StySmall", "account-ft-earned-daily", P.rewards, { StringAlign: "Right" })
sec("MeterDailyChart", { Meter: "Shape", X: 26, Y: 560, Hidden: 1, Shape: "Rectangle 0,0,1,1 | Fill Color 0,0,0,0 | StrokeWidth 0", LeftMouseUpAction: open("account-ft-earned-daily", P.rewards) })
text("MeterDailyStart", "StySmall", "account-ft-earned-daily", P.rewards)
text("MeterDailyEnd", "StySmall", "account-ft-earned-daily", P.rewards, { StringAlign: "Right" })

// ---- Positions tab
L.push("", "; ---------------------------------------------------------------- Positions tab")
text("MeterPosHead", "StyCap", "positions-header", P.portfolio, { Text: "POSITIONS", W: 160 })
text("MeterPosCount", "StySmall", "positions-header", P.portfolio, { StringAlign: "Right", W: 100 })
text("MeterPosEmpty", "StySub", "positions-empty", P.portfolio, { W: 300 })
for (let i = 1; i <= 6; i++) {
  text("MeterPosBadge" + i, "StyText", "positions-row", P.portfolio, { W: 28, H: 28, StringAlign: "CenterCenter", StringStyle: "Bold", FontColor: "183,177,255,255" })
  text("MeterPos" + i, "StyText", "positions-row", P.portfolio, { W: 70, StringStyle: "Bold" })
  text("MeterPosSide" + i, "StySmall", "positions-row", P.portfolio, { W: 54, H: 14, StringAlign: "CenterCenter", StringStyle: "Bold" })
  text("MeterPosNet" + i, "StySmall", "positions-row", P.portfolio, { W: 110 })
  text("MeterPosMark" + i, "StySmall", "positions-row", P.portfolio, { W: 100, FontColor: "161,161,170,255" })
  text("MeterPosEntry" + i, "StySmall", "positions-row", P.portfolio, { W: 100 })
  text("MeterPosPnl" + i, "StyText", "positions-row", P.portfolio, { W: 90, StringAlign: "Right", StringStyle: "Bold" })
  text("MeterPosPct" + i, "StySmall", "positions-row", P.portfolio, { W: 90, StringAlign: "Right" })
}
text("MeterPtsHead", "StyCap", "account-points-positions", P.pointsActivity, { Text: "POINTS POSITIONS", W: 200 })
for (let i = 1; i <= 5; i++) {
  text("MeterPtsName" + i, "StyText", "account-points-positions", P.pointsActivity, { W: 170 })
  text("MeterPtsUsd" + i, "StySub", "account-points-positions", P.pointsActivity, { W: 90, StringAlign: "Right" })
  text("MeterPtsMult" + i, "StySub", "account-points-positions", P.pointsActivity, { W: 50, StringAlign: "Right", FontColor: "183,177,255,255" })
}
text("MeterPutsHead", "StyCap", "account-ftput-positions", P.put, { Text: "FTPUT POSITIONS", W: 300 })
for (let i = 1; i <= 4; i++) {
  text("MeterPutsName" + i, "StyText", "account-ftput-positions", P.put, { W: 130 })
  text("MeterPutsCost" + i, "StySub", "account-ftput-positions", P.put, { W: 130, StringAlign: "Right" })
  text("MeterPutsSince" + i, "StySub", "account-ftput-positions", P.put, { W: 60, StringAlign: "Right" })
}

// ---- footer (always shown, placed under the tab's last card)
L.push("", "; ---------------------------------------------------------------- footer")
text("MeterStatus", "StySmall", "footer-updated", SITE, { Text: "loading...", W: 200, Hidden: 0 })
text("MeterBtnDashboard", "StyText", "footer-open-site", SITE, { Text: "Open flyingtulip.com [\\x2192]", StringAlign: "Right", W: 200, FontColor: "147,133,255,255", Hidden: 0 })
text("MeterDisclaimer", "StySmall", "footer-disclaimer", SITE, { Text: "Public API only, no keys. Not financial advice.", W: 352, Hidden: 0 })

fs.writeFileSync(OUT, L.join("\n").replace(/^\n/, "") + "\n")
console.log("wrote " + path.relative(process.cwd(), OUT))
