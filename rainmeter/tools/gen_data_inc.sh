#!/usr/bin/env bash
# Regenerates Skins/FlyingTulip/@Resources/Data.inc (the WebParser measures). Usage: tools/gen_data_inc.sh
set -eu
cd "$(dirname "$0")/.."
OUT="Skins/FlyingTulip/@Resources/Data.inc"
{
echo "; WebParser downloads. Every file is written to DownloadFile\\ inside the skin folder and parsed by Lua"
echo "; (FinishAction -> OnData). Generated by tools/gen_data_inc.sh: edit that script, not this file."
gen() { # name file url group rate disabled key
  local ua='Mozilla/5.0 (Windows NT 10.0; Win64; x64) FlyingTulipRainmeter/1.0'
  printf '\n[Measure%s]\nMeasure=WebParser\nURL=%s\nDownload=1\nDownloadFile=%s\nUpdateRate=%s\nDynamicVariables=1\nUserAgent=%s\n' "$1" "$3" "$2" "$5" "$ua"
  if [ -n "$4" ]; then printf 'Group=%s\n' "$4"; fi
  if [ "$6" = 1 ]; then printf 'Disabled=1\n'; fi
  printf 'FinishAction=[!CommandMeasure MeasureScript "OnData('"'%s'"')"]\n' "$7"
  printf 'OnConnectErrAction=[!CommandMeasure MeasureScript "OnError('"'%s'"')"]\n' "$7"
  printf 'OnDownloadErrAction=[!CommandMeasure MeasureScript "OnError('"'%s'"')"]\n' "$7"
}
A=https://api.flyingtulip.com
gen Price price.json "$A/mm/spot/tickers?chainId=#PriceChainId#" Data '#RefreshSeconds#' 0 price
gen Fees fees.json "$A/fees/application?period=1d&granularity=day" Data '#RefreshSeconds#' 0 fees
gen FeesSeries fees_series.json "$A/fees/application?period=1m&granularity=day" Data 600 0 feesSeries
gen Klines klines.json "$A/mm/spot/market/klines?symbol=FT-ftUSD&chainId=#PriceChainId#&interval=1d&limit=30" Data 600 0 klines
gen Lend lend.json "$A/mm/lend?user=#Wallet#" Account '#RefreshSeconds#' 1 lend
gen Lend143 lend143.json "$A/mm/lend?user=#Wallet#&chainId=143" Account '#RefreshSeconds#' 1 lend143
for c in 146 1 56 143; do gen "Sum$c" "sum$c.json" "$A/mm/spot/account/summary?address=#Wallet#&chainId=$c" Account '#RefreshSeconds#' 1 "sum$c"; done
gen Rewards rewards.json "$A/account/dashboard?address=#Wallet#&view=rewards" Account '#RefreshSeconds#' 1 rewards
gen Points points.json "$A/points?walletAddress=#Wallet#" Account '#RefreshSeconds#' 1 points
for c in 146 1 56; do gen "Pos$c" "pos$c.json" "$A/mm/spot/account/positions?address=#Wallet#&chainId=$c" Account '#RefreshSeconds#' 1 "pos$c"; done
gen Puts puts.json "$A/tge/ftPUT/user/#Wallet#" Account '#RefreshSeconds#' 1 puts
# leaderboard rank search: enabled by Lua one page at a time, disabled again after each answer
gen Rank rank.json "$A/points/leaderboard?page=#RankPage#&limit=500" '' 1 1 rank
} > "$OUT"
echo "wrote $OUT"
