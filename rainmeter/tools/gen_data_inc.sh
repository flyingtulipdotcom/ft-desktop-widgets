#!/usr/bin/env bash
# Regenerates Skins/FlyingTulip/@Resources/Data.inc (the WebParser measures). Usage: tools/gen_data_inc.sh
set -eu
cd "$(dirname "$0")/.."
OUT="Skins/FlyingTulip/@Resources/Data.inc"
{
echo "; WebParser measures. Each one fetches an endpoint into memory: RegExp (?s)^(.*)\$ captures the whole JSON body"
echo "; as the measure's string value, then FinishAction calls OnData(key) and the Lua reads it with"
echo "; SKIN:GetMeasure(name):GetStringValue(). Nothing is written to disk."
echo "; Generated by tools/gen_data_inc.sh: edit that script, not this file."
gen() { # name url group rate disabled key [dynamic]
  local ua='Mozilla/5.0 (Windows NT 10.0; Win64; x64) FlyingTulipRainmeter/1.4.0'
  printf '\n[Measure%s]\nMeasure=WebParser\nURL=%s\n' "$1" "$2"
  printf 'RegExp=(?s)^(.*)$\nStringIndex=1\nUpdateRate=%s\n' "$4"
  printf 'Flags=ForceReload|NoCookies|NoCacheWrite\nHeader=Accept: application/json\nUserAgent=%s\n' "$ua"
  if [ "${7:-0}" = 1 ]; then printf 'DynamicVariables=1\n'; fi
  if [ -n "$3" ]; then printf 'Group=%s\n' "$3"; fi
  if [ "$5" = 1 ]; then printf 'Disabled=1\n'; fi
  printf 'FinishAction=[!CommandMeasure MeasureScript "OnData('"'%s'"')"]\n' "$6"
  printf 'OnConnectErrorAction=[!CommandMeasure MeasureScript "OnError('"'%s'"')"]\n' "$6"
  printf 'OnRegExpErrorAction=[!CommandMeasure MeasureScript "OnError('"'%s'"')"]\n' "$6"
}
A=https://api.flyingtulip.com
gen Price "$A/mm/spot/tickers?chainId=#PriceChainId#" Data '#RefreshSeconds#' 0 price
gen Fees "$A/fees/application?period=1d&granularity=day" Data '#RefreshSeconds#' 0 fees
gen FeesSeries "$A/fees/application?period=1m&granularity=day" Data 600 0 feesSeries
gen Klines "$A/mm/spot/market/klines?symbol=FT-ftUSD&chainId=#PriceChainId#&interval=1d&limit=30" Data 600 0 klines
# /mm/lend is about 500 KB. The Lua slows it to every 10 minutes while the wallet has no debt on any chain.
gen Lend "$A/mm/lend?user=#CurWallet#" Account '#RefreshSeconds#' 1 lend 1
gen Lend143 "$A/mm/lend?user=#CurWallet#&chainId=143" Account '#RefreshSeconds#' 1 lend143 1
for c in 146 1 56 143; do gen "Sum$c" "$A/mm/spot/account/summary?address=#CurWallet#&chainId=$c" Account '#RefreshSeconds#' 1 "sum$c" 1; done
gen Rewards "$A/account/dashboard?address=#CurWallet#&view=rewards" Account '#RefreshSeconds#' 1 rewards 1
gen Points "$A/points?walletAddress=#CurWallet#" Account '#RefreshSeconds#' 1 points 1
for c in 146 1 56; do gen "Pos$c" "$A/mm/spot/account/positions?address=#CurWallet#&chainId=$c" Account '#RefreshSeconds#' 1 "pos$c" 1; done
gen Puts "$A/tge/ftPUT/user/#CurWallet#" Account '#RefreshSeconds#' 1 puts 1
gen Hist "$A/account/rewards/history?address=#CurWallet#&range=#HistRange#" Account 600 1 hist 1
gen PtsRows "$A/points/breakdown?walletAddress=#CurWallet#&page=1&limit=50" Account 600 1 ptsRows 1
# background health check of the wallets that are not shown: the Lua sets WatchWallet and forces one fetch at a
# time (same pattern as the rank search), so each extra wallet adds one /mm/lend read per RefreshSeconds while it
# has debt and one per 10 minutes otherwise.
gen Watch "$A/mm/lend?user=#WatchWallet#" '' 3600 1 watch 1
gen Watch143 "$A/mm/lend?user=#WatchWallet#&chainId=143" '' 3600 1 watch143 1
# leaderboard rank search: the Lua sets RankPage, enables the measure and forces one fetch per page with
# !CommandMeasure MeasureRank "Update"; the long UpdateRate keeps it from refetching on its own.
gen Rank "$A/points/leaderboard?page=#RankPage#&limit=500" '' 3600 1 rank 1
} > "$OUT"
echo "wrote $OUT"
